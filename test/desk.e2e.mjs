// End-to-end test of the Desk app on a phone-sized screen, against the real API (file store).
// Needs: `npm run build` first. Run: node test/desk.e2e.mjs [outDir for screenshots]
import { spawn } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { createRequire } from 'node:module'
const { chromium } = createRequire(import.meta.url)('/opt/node22/lib/node_modules/playwright')
import { addDays, nowParts } from '../shared/schedule.js'

const PASS = 'correct horse battery'
const out = process.argv[2]
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'deske2e-'))
let pass = 0, fail = 0
const ok = (c, m) => { c ? pass++ : fail++; console.log(`${c ? '  ✓' : '  ✗ FAIL'} ${m}`) }

const api = spawn(process.execPath, ['dev-server.mjs'], { env: { ...process.env, API_PORT: '8787', DESK_PASSPHRASE: PASS, DESK_ORIGIN: 'http://localhost:4173', DESK_DEV_STORE: path.join(tmp, 's.json') }, stdio: ['ignore', 'pipe', 'inherit'] })
const prev = spawn('npx', ['vite', 'preview', '--port', '4173', '--strictPort'], { stdio: 'ignore' })
await new Promise((r) => api.stdout.on('data', (d) => String(d).includes('api on') && r()))
await new Promise((r) => setTimeout(r, 2500))

const BASE = 'http://localhost:4173'
const pub = (p, body) => fetch(`${BASE}/api/public/${p}`, { method: body ? 'POST' : 'GET', headers: { 'content-type': 'application/json', 'x-forwarded-for': '10.2.2.' + Math.floor(Math.random() * 250) }, body: body ? JSON.stringify(body) : undefined }).then((r) => r.json())
const tomorrow = addDays(nowParts().date, 1)
const firstSlots = (await pub(`slots?date=${tomorrow}&type=new&mode=clinic`)).slots
const bookTomorrow = (i, name) => pub('book', { name, phone: `98765${43200 + i}`, type: 'new', mode: 'clinic', date: tomorrow, start: firstSlots[i], note: 'Recurring headache' })
await bookTomorrow(0, 'Asha Patel')
await bookTomorrow(2, 'Ravi Shah')

const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 })
const page = await ctx.newPage()
page.setDefaultTimeout(30000)
const errs = []
page.on('pageerror', (e) => errs.push(e.message))
page.on('console', (m) => m.type() === 'error' && !/Failed to load resource/.test(m.text()) && errs.push(m.text()))
const shot = (n) => out && page.screenshot({ path: path.join(out, `desk-${n}.png`) })
const tab = (name) => page.click(`.dk-tabs button:has-text("${name}")`)

console.log('1. sign in')
await page.goto(BASE + '/desk/')
await page.waitForSelector('.dk-login')
ok((await page.locator('.dk-login h1').textContent()) === 'Avighna Desk', 'login screen shows')
ok((await page.locator('button:has-text("Face ID")').count()) === 0, 'no Face ID button before it is set up')
await shot('1-login')
await page.fill('input[type=password]', 'wrong wrong wrong')
await page.click('.dk-login form button')
await page.waitForSelector('.dk-err')
ok(/not right/i.test(await page.locator('.dk-err').textContent()), 'wrong passphrase is refused with a plain message')
await page.fill('input[type=password]', PASS)
await page.click('.dk-login form button')
await page.waitForSelector('.dk-top h1')
ok((await page.locator('.dk-top h1').textContent()) === 'Today', 'right passphrase opens Today')
ok((await page.evaluate(() => document.cookie)) === '', 'session cookie is not readable by page scripts (HttpOnly)')
await shot('2-today')

console.log('2. requests, confirm, decline')
ok(/2/.test(await page.locator('.dk-tabs i').textContent()), 'Requests tab shows a badge with 2')
ok(/2 new requests/.test(await page.locator('.dk-alert').textContent()), 'Today shows "2 new requests waiting"')
await tab('Requests')
ok((await page.locator('.dk-row').count()) === 2, 'both requests are listed')
await shot('3-requests')
await page.locator('.dk-row', { hasText: 'Asha Patel' }).click()
await page.waitForSelector('.dk-sheet')
ok(/Recurring headache/.test(await page.locator('.dk-quote').textContent()), 'patient note is visible')
ok((await page.locator('a.dk-btn:has-text("Call")').getAttribute('href')) === 'tel:+919876543200', 'Call button dials the patient')
await shot('4-sheet')
await page.click('button:has-text("Confirm")')
await page.waitForSelector('.dk-tell')
const msg = await page.inputValue('.dk-tell')
ok(/Hello Asha/.test(msg) && /is confirmed for/.test(msg) && /Tarsali/.test(msg), 'confirmation message is pre-written with name, time and address')
const waHref = await page.locator('a:has-text("Send on WhatsApp")').getAttribute('href')
ok(/^https:\/\/wa\.me\/919876543200\?text=/.test(waHref), 'WhatsApp link goes to that one patient only')
await shot('5-tell')
await page.click('button:has-text("Skip")')
ok(/1/.test(await page.locator('.dk-tabs i').textContent()), 'badge drops to 1')
await page.locator('.dk-row', { hasText: 'Ravi Shah' }).click()
await page.click('button:has-text("Decline")')
await page.waitForSelector('.dk-tell')
ok(/not available/.test(await page.inputValue('.dk-tell')), 'decline message is pre-written')
await page.click('button:has-text("Skip")')
ok((await page.locator('.dk-tabs i').count()) === 0, 'no more waiting requests')
const slotsNow = (await pub(`slots?date=${tomorrow}&type=new&mode=clinic`)).slots
ok(slotsNow.includes(firstSlots[2]) && !slotsNow.includes(firstSlots[0]), "declined time is free again, confirmed time stays taken")

console.log('3. add an appointment, time off, settings')
await tab('Calendar')
await page.click('button:has-text("+ Add appointment")')
await page.waitForSelector('.dk-sheet')
await page.fill('.dk-form input[autocomplete=off]', 'Meera Joshi')
await page.fill('.dk-form input[type=tel]', '91234 56780')
await page.fill('.dk-form input[type=date]', addDays(nowParts().date, 2))
await page.waitForSelector('.dk-slots button')
await page.locator('.dk-slots button').nth(1).click()
await shot('6-add')
await page.click('button:has-text("Add to calendar")')
await page.waitForSelector('.dk-sheet', { state: 'detached' })
ok((await page.locator('.dk-row', { hasText: 'Meera Joshi' }).count()) === 1, 'new appointment appears in the calendar')
await page.click('button:has-text("Time off")')
await page.waitForSelector('.dk-sheet')
await page.fill('.dk-sheet input[type=date]', addDays(nowParts().date, 3))
await page.fill('.dk-sheet input[placeholder*="Holiday"]', 'Seminar')
await page.click('button:has-text("Block this time")')
await page.waitForSelector('[role=status]')
const blocked = (await pub(`slots?date=${addDays(nowParts().date, 3)}&type=new&mode=clinic`)).slots
ok(blocked.length === 0, 'blocked day has no bookable slots on the website')
await page.click('.dk-x')
ok((await page.locator('.dk-off', { hasText: 'Seminar' }).count()) === 1, 'time off shows in the calendar')
await shot('7-calendar')
await tab('Settings')
await page.waitForSelector('.dk-more')
ok((await page.locator('.dk-install').count()) === 1, 'iPhone "Add to Home Screen" help is shown (not installed)')
await page.locator('.dk-switch input').check()
await page.waitForSelector('.dk-toast')
ok((await pub('config')).autoConfirm === true, 'auto-confirm switch is saved on the server')
await page.locator('.dk-switch input').uncheck()
await shot('8-settings')

console.log('4. Face ID (virtual authenticator)')
const cdp = await ctx.newCDPSession(page)
await cdp.send('WebAuthn.enable')
await cdp.send('WebAuthn.addVirtualAuthenticator', { options: { protocol: 'ctap2', transport: 'internal', hasResidentKey: true, hasUserVerification: true, isUserVerified: true, automaticPresenceSimulation: true } })
await page.click('button:has-text("Set up Face ID")')
await page.waitForSelector('.dk-toast:has-text("Face ID is set up")')
ok(true, 'Face ID registered with user verification required')
await page.click('button:has-text("Sign out here")')
await page.waitForSelector('.dk-login')
ok((await page.locator('button:has-text("Unlock with Face ID")').count()) === 1, 'login now offers Face ID')
await shot('9-login-faceid')
await page.click('button:has-text("Unlock with Face ID")')
await page.waitForSelector('.dk-top h1')
ok((await page.locator('.dk-top h1').textContent()) === 'Today', 'Face ID signs her in without the passphrase')

console.log('5. security')
const cookies = await ctx.cookies()
const sess = cookies.find((c) => c.name === 'desk')
ok(sess && sess.httpOnly && sess.sameSite === 'Strict', 'session cookie is HttpOnly + SameSite=Strict')
await tab('Settings')
page.once('dialog', (d) => d.accept())
await page.click('button:has-text("Sign out on all devices")')
await page.waitForSelector('.dk-login')
const stale = await fetch(`${BASE}/api/desk/list`, { headers: { cookie: `desk=${sess.value}` } })
ok(stale.status === 401, 'the old session no longer works after "sign out on all devices"')
const anon = await fetch(`${BASE}/api/desk/list`)
ok(anon.status === 401, 'the Desk API refuses anyone without a session')
const page2 = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage()
await page2.goto(BASE + '/desk/')
await page2.waitForSelector('.dk-login')
ok((await page2.locator('.dk-top, .dk-row').count()) === 0, "a stranger's browser sees only the sign-in screen, no patient data")
ok(errs.length === 0, 'no console errors' + (errs.length ? ': ' + errs[0] : ''))

await browser.close()
api.kill(); prev.kill()
console.log(`\n${pass} passed, ${fail} failed`)
process.exit(fail ? 1 : 0)
